UNPUBLISH = [5671314]  # «Новые продукты Luxhommè… уже скоро», 30.06.2025: устарела, на витрине 404


def call(url, data=None):
    req = urllib.request.Request(url, method="POST" if data else "GET",
                                 data=json.dumps(data).encode() if data else None,
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


def check():
    for i, t in EXCERPTS.items():
        assert 120 <= len(t) <= 160, (i, len(t), t)
        assert "—" not in t, (i, t)
        assert t.endswith((".", "?")), (i, t)


if __name__ == "__main__":
    check()
    cmd = sys.argv[1]
    ids = sorted(set(EXCERPTS) | set(UNPUBLISH))
    if cmd == "check":
        print("ok", len(EXCERPTS), "описаний", min(map(len, EXCERPTS.values())), "-", max(map(len, EXCERPTS.values())), "знаков")
    elif cmd == "backup":
        rows = call(f"{API}?include={','.join(map(str, ids))}&per_page=100&status=publish,draft&context=edit&_fields=id,slug,status,excerpt")
        json.dump([{"id": r["id"], "slug": r["slug"], "status": r["status"], "excerpt": r["excerpt"]["raw"]} for r in rows],
                  open(sys.argv[2], "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        print("backup:", len(rows))
    elif cmd == "apply":
        only = set(map(int, sys.argv[2:]))
        for i in ids:
            if only and i not in only:
                continue
            body = {"status": "draft"} if i in UNPUBLISH else {"excerpt": EXCERPTS[i]}
            r = call(f"{API}/{i}", body)
            got = r["status"] if i in UNPUBLISH else r["excerpt"]["raw"]
            print(i, "ok" if got == body.get("status", body.get("excerpt")) else "MISMATCH", r["slug"])
    elif cmd == "restore":
        for row in json.load(open(sys.argv[2], encoding="utf-8")):
            r = call(f"{API}/{row['id']}", {"excerpt": row["excerpt"], "status": row["status"]})
            print(row["id"], r["status"])
