def call(url, data=None):
    req = urllib.request.Request(url, method="POST" if data else "GET",
                                 data=json.dumps(data).encode() if data else None,
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


def check():
    for i, (old, new) in TITLES.items():
        assert len(new + SUFFIX) <= 70, (i, len(new + SUFFIX), new)
        assert "—" not in new, (i, new)


if __name__ == "__main__":
    check()
    cmd = sys.argv[1]
    if cmd == "check":
        print("ok", len(TITLES))
    elif cmd == "table":
        print("| id | Сейчас (title, знаков) | Предлагаем (title, знаков) |\n|---|---|---|")
        for i, (old, new) in sorted(TITLES.items(), key=lambda x: -len(x[1][0])):
            print(f"| {i} | {old.strip()} ({len(old.strip() + SUFFIX)}) | {new} ({len(new + SUFFIX)}) |")
    elif cmd == "backup":
        rows = call(f"{API}?include={','.join(map(str, TITLES))}&per_page=100&context=edit&_fields=id,slug,title")
        json.dump([{"id": r["id"], "slug": r["slug"], "title": r["title"]["raw"]} for r in rows],
                  open(sys.argv[2], "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        print("backup:", len(rows))
    elif cmd == "apply":
        only = set(map(int, sys.argv[2:]))
        for i, (old, new) in TITLES.items():
            if only and i not in only:
                continue
            r = call(f"{API}/{i}", {"title": new})
            print(i, "ok" if r["title"]["raw"] == new else "MISMATCH", r["slug"])
    elif cmd == "restore":
        for row in json.load(open(sys.argv[2], encoding="utf-8")):
            r = call(f"{API}/{row['id']}", {"title": row["title"]})
            print(row["id"], r["title"]["raw"][:60])
