"""Статья «Подарок маме по бюджету» (план: 26.11.2026). Цены и группы по бюджету берутся из каталога при сборке.
usage: python3 -I build_post_02.py [--draft]   без --draft только собирает post_02.json, с --draft создаёт/обновляет черновик в WP"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lux_blog import Doc, P, S, MUTED, DIES, catalog, rub, link, save_draft, check

HERE = os.path.dirname(os.path.abspath(__file__))
TITLE = "Подарок маме по бюджету: до 5\u00a0000, 10\u00a0000 и 20\u00a0000\u00a0₽"
SLUG = "podarok-mame-po-byudzhetu"
COVER = 5683328  # luxhomme-mothers-day-hero.jpg: кофемашина и подарок, не использовалась

cat = catalog()
items = sorted(((cat[s][0], s) for s in P if s in cat and cat[s][1]), key=lambda x: x[0])
G = [("do-5000", "До 5 000 ₽", 0, 5000), ("do-10000", "До 10 000 ₽", 5000, 10000), ("do-20000", "До 20 000 ₽", 10000, 20000)]
groups = {a: [(p, s) for p, s in items if lo < p <= hi] for a, _, lo, hi in G}
more = [(p, s) for p, s in items if p > 20000]
cheapest = items[0][0]
assert all(groups.values()), groups

d = Doc()
d.para("Когда бюджет на подарок понятен, выбирать проще. Мы разделили технику Luxhommè на три группы по цене и для каждого товара "
       "написали, кому из мам он подойдёт. День матери в 2026 году 29 ноября, поэтому в конце подсказываем, как успеть с заказом.",
       "font-size:19px;line-height:1.6;margin-bottom:28px;")
d.summary("Если коротко", f"Полезный подарок маме от {rub(cheapest)}: выберите группу по бюджету",
          [(t, f"{len(groups[a])} {'подарка' if len(groups[a]) < 5 else 'подарков'}", f"от {rub(groups[a][0][0])}", a) for a, t, _, _ in G])
d.toc([("do-5000", "Подарки маме до 5 000 ₽"), ("do-10000", "Подарки маме до 10 000 ₽"), ("do-20000", "Подарки маме до 20 000 ₽"),
       ("bolshe", "Если бюджет больше"), ("tablica", "Все подарки в одной таблице"), ("kak-vybrat", "Как выбрать внутри бюджета"),
       ("uspet", "Как успеть к 29 ноября"), ("faq", "Вопросы и ответы")])

leads = {"do-5000": "Недорогой подарок маме, который не выглядит формальным: техника для ежедневных дел.",
         "do-10000": "В этой группе самый широкий выбор: кофе по утрам, уборка, окна и тренировки дома.",
         "do-20000": "Подарок, который берёт на себя целое домашнее дело: готовку на всю семью, уборку ковров и мебели, кофе с молочной пенкой."}
for n, (a, t, _, _) in enumerate(G, 1):
    d.h2(f"0{n}", f"Подарки маме {t.lower()}", a)
    d.para(leads[a])
    for p, s in groups[a]:
        d.card(s, p, "Маме, которая")
    if a == "do-20000":
        d.note("Важно", f'Если у мамы есть заболевания суставов, сердца, повышенное давление или другие хронические заболевания, перед занятиями на виброплатформе стоит посоветоваться с врачом. '
               f'Чем отличаются модели: {link("/blog/2d-ili-3d-vibroplatforma-raznica", "2D или 3D виброплатформа")}.')

d.h2("04", "Если бюджет больше", "bolshe")
for p, s in more:
    d.card(s, p, "Маме, которая")
d.para(f'Как выбрать между капсульной и зерновой: {link("/blog/kapsulnaya-ili-zernovaya-kofemashina-chto-luchshe-dlya-doma", "капсульная или зерновая кофемашина")}.')

d.h2("05", "Все подарки маме в одной таблице", "tablica")
d.table(["Подарок", "Цена", "Маме, которая"],
        [[(link(f"/products/{s}", P[s][0]), "font-weight:500;"), (rub(p), "white-space:nowrap;font-weight:700;"), (P[s][2], f"color:{MUTED};")] for p, s in items],
        "Цены указаны по каталогу Luxhommè на момент публикации.")

d.h2("06", "Как выбрать подарок внутри бюджета", "kak-vybrat")
d.steps([("Уберите самое нелюбимое дело", "Если не знаете, чего хочет мама, выбирайте то, что убирает самое нелюбимое дело. Чаще всего это мытьё полов и готовка."),
         ("Дарите следующий уровень", "Если мама уже пользуется похожей техникой, подарите следующий шаг: вместо обычной швабры паровую, вместо духовки аэрогриль."),
         ("Сложите бюджет", "Если подарок от нескольких человек, сложите бюджет: так можно подарить вещь из группы до 20 000 ₽.")])

d.h2("07", "Как успеть к 29 ноября", "uspet")
d.dark("Чёрная пятница продолжается", "−20%", "на весь заказ на luxhomme.store",
       "Введите код при оформлении заказа: скидка действует и на подарок маме. Срок доставки в ваш город проверьте при оформлении или уточните в службе заботы.",
       "Выбрать подарок маме →", f"{S}/catalog", code="BLACK20")

d.resume(f"Подарок маме по бюджету проще выбрать, если начать с суммы, а потом решить, какое дело он возьмёт на себя. "
         f"До 5 000 ₽ это паровая швабра или виброплатформа, до 10 000 ₽ кофемашина, швабра с отпаривателем или робот для окон, "
         f"до 20 000 ₽ аэрогриль с двумя чашами, моющий пылесос или рожковая кофемашина. Больше идей по увлечениям мамы: "
         f'{link("/blog/chto-podarit-mame-na-den-materi", "что подарить маме на День матери")}.')

d.h2("08", "Вопросы и ответы", "faq")
lst = lambda g: ", ".join(f"{P[s][0].split(' ', 1)[0].lower()} {P[s][0].split(' ', 1)[1]} ({rub(p)})" for p, s in g)
d.faq([("Что подарить маме до 5 000 ₽?", f"Из техники Luxhommè: {lst(groups['do-5000'])}. Цены по каталогу на момент публикации."),
       ("Что подарить маме до 10 000 ₽?", f"{lst(groups['do-10000'])[0].upper()}{lst(groups['do-10000'])[1:]}."),
       ("Что лучше подарить: аэрогриль или кофемашину?", f'Аэрогриль, если мама много готовит и хочет меньше стоять у плиты. Кофемашину, если для неё важен спокойный утренний кофе. '
        f'Сравнение аэрогриля с духовкой: {link("/blog/aerogril-ili-duhovka-chto-luchshe-vybrat-dlya-doma", "аэрогриль или духовка")}.'),
       ("Как выбрать паровую швабру в подарок?", f'Для квартиры хватит лёгкой EcoSteam Pro. Если маме пригодится отпаривание одежды, выбирайте SC-100 Max. '
        f'Подробно: {link("/blog/kak-vybrat-parovuyu-shvabru-dlya-kvartiry-i-chastnogo-doma", "как выбрать паровую швабру")}.'),
       ("Что подарить маме, если скидываемся всей семьёй?", "Сложите бюджет и выберите вещь из группы до 20 000 ₽: аэрогриль AirChef Dual Pro для большой семьи, моющий пылесос для ковров и мебели или кофемашину Caffio Professional для капучино.")])

content = d.html()
excerpt = (f"Подарки маме на День матери по бюджету: техника Luxhommè до 5 000, 10 000 и 20 000 ₽. "
           f"Кофемашины, аэрогрили, паровые швабры от {rub(cheapest)}.")
check(TITLE, excerpt, content)
json.dump({"title": TITLE, "slug": SLUG, "content": content, "excerpt": excerpt, "featured_media": COVER},
          open(os.path.join(HERE, "post_02.json"), "w"), ensure_ascii=False)
print("группы:", {a: [(s, p) for p, s in g] for a, g in groups.items()}, "| больше:", more)
print(len(content), "символов, description", len(excerpt))
if "--draft" in sys.argv:
    r = save_draft(os.path.join(HERE, "draft_02.json"), TITLE, SLUG, content, excerpt, COVER)
    print("черновик:", r["id"], r["status"], f"https://luxhomme.store/wp-admin/post.php?post={r['id']}&action=edit")
